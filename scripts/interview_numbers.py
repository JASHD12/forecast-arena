"""Generate `docs/interview/numbers.md` (T170): every number the interview kit may quote.

    python scripts/interview_numbers.py                     # refresh backtests and evals
    python scripts/interview_numbers.py --ledger DIR        # also refresh the live snapshot
    python scripts/interview_numbers.py --check             # fail if backtests/evals are stale

Sources, all computed by code (integrity rule I5):
- backtests: the committed model cards in `docs/models/` (labelled as backtests, I4);
- evaluations: the committed LLM eval results in `evals/results/` (labelled as evaluations);
- live record: `arena report cv` and `ledger verify` on a checkout of the ledger branch,
  stamped with the ledger commit. It changes daily, so `--check` does not compare it.
"""

import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

OUT = ROOT / "docs" / "interview" / "numbers.md"
CARDS = (("power", "Electricity, champion vs baselines"),
         ("power-lgbm", "Electricity, LightGBM challenger"),
         ("power-mlp", "Electricity, PyTorch network challenger"),
         ("power-ts", "Electricity, time-series benchmarks"),
         ("attention", "Wikipedia attention"),
         ("markets", "Exchange rates"))  # fmt: skip

HEAD = """# Numbers for the interview kit (generated)

Generated by `scripts/interview_numbers.py`; do not edit by hand. Every figure quoted in
`docs/interview/` appears here, with where it comes from. Three kinds of number, never
mixed: **backtests** (past days replayed through the production code), **evaluations**
(a frozen golden set of past questions sent to the real model), and the **live record**
(the public ledger). Lower Brier is better; always answering 50% scores 0.25.
"""


def _tables(md: str) -> list[str]:
    """The markdown tables of a card that start with Forecaster or Comparison."""
    out, cur = [], []
    for ln in md.splitlines():
        if ln.startswith(("| Forecaster |", "| Comparison |")):
            cur = [ln]
        elif cur and ln.startswith("|"):
            cur.append(ln)
        elif cur:
            out.append("\n".join(cur))
            cur = []
    if cur:
        out.append("\n".join(cur))
    return out


def backtests() -> str:
    parts = ["## Backtests (not the live record)"]
    for stem, title in CARDS:
        md = (ROOT / "docs" / "models" / f"{stem}.md").read_text(encoding="utf-8")
        span = re.search(r"Batches (\S+) to (\S+) \((\d+) batch days\)", md)
        when = f" - {span.group(1)} to {span.group(2)}, {span.group(3)} batch days" if span else ""
        parts.append(f"### {title}{when}\n\nSource: `docs/models/{stem}.md`\n\n"
                     + "\n\n".join(_tables(md)))  # fmt: skip
    return "\n\n".join(parts)


def _pct(x: float | None) -> str:
    return "-" if x is None else f"{100 * x:.0f}%"


def evals() -> str:
    parts = ["## LLM evaluations (golden set of past questions; not the live record)"]
    for f in sorted((ROOT / "evals" / "results").glob("eval-*.json")):
        d = json.loads(f.read_text(encoding="utf-8"))
        rows = ["| Forecaster | Model | n | Answered | Brier | Base rate, same items | "
                "Valid JSON first try | Repair rate | Cost (USD) | Output tokens |",
                "|---|---|---|---|---|---|---|---|---|---|"]  # fmt: skip
        for fid, m in sorted(d["metrics"].items()):
            rows.append(
                f"| {fid} | {m['model']} | {m['n']} | {m['answered']} | {m['brier']:.4f} | "
                f"{m['base_rate_brier_same_items']:.4f} | {_pct(m['json_valid_first_try'])} | "
                f"{_pct(m['repair_rate'])} | {m['cost_usd']:.4f} | {m['output_tokens']} |"
            )
        paired = "; ".join(
            f"{p['a']} - {p['b']}: {p['diff']:+.4f} [{p['lo']:+.4f}, {p['hi']:+.4f}] "
            f"on {p['n']} items"
            for p in d.get("paired", [])
        )
        caps = d["caps"]
        parts.append(
            f"### Run `{d['run_id']}` ({d['n_items']} items; caps {caps['max_requests']} "
            f"requests, {caps['max_tokens']} tokens)\n\nSource: `evals/results/{f.name}`\n\n"
            + "\n".join(rows)
            + (f"\n\nPaired Brier difference: {paired}" if paired else "")
        )
    return "\n\n".join(parts)


def live(ledger: Path) -> str:
    def arena(*args: str) -> str:
        cmd = [str(ROOT / ".venv" / "bin" / "arena"), "--ledger-dir", str(ledger), *args]
        return subprocess.run(cmd, capture_output=True, text=True, check=True).stdout.strip()

    sha = subprocess.run(["git", "-C", str(ledger), "log", "-1", "--format=%h %cI"],
                         capture_output=True, text=True, check=True).stdout.strip()  # fmt: skip
    verify = arena("ledger", "verify").splitlines()[0]
    return (f"## Live record (ledger commit {sha})\n\nSource: `arena report cv` and "
            f"`arena ledger verify` on the ledger branch.\n\n```\n{arena('report', 'cv')}\n"
            f"{verify}\n```")  # fmt: skip


def block(name: str, body: str) -> str:
    return f"<!-- {name}:start -->\n{body}\n<!-- {name}:end -->"


def _old(text: str, name: str) -> str | None:
    m = re.search(rf"<!-- {name}:start -->\n(.*?)\n<!-- {name}:end -->", text, re.S)
    return m.group(1) if m else None


def render(old: str, ledger: Path | None) -> str:
    live_body = live(ledger) if ledger else (_old(old, "live") or
                                             "## Live record\n\nNot generated yet.")  # fmt: skip
    return "\n\n".join([HEAD.rstrip(), block("backtests", backtests()), block("evals", evals()),
                        block("live", live_body)]) + "\n"  # fmt: skip


def main(argv: list[str]) -> int:
    old = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
    ledger = Path(argv[argv.index("--ledger") + 1]) if "--ledger" in argv else None
    new = render(old, ledger)
    if "--check" in argv:
        if new != old:
            print("docs/interview/numbers.md is stale: run python scripts/interview_numbers.py")
            return 1
        print("interview numbers up to date")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(new, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
