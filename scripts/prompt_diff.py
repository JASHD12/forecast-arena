"""Show what changed between consecutive versions of every prompt (T383).

    python scripts/prompt_diff.py            # rewrite docs/prompts/CHANGES.md
    python scripts/prompt_diff.py --check    # fail if the file is stale

Prompt files are `src/arena/llm/prompts/<name>_v<N>.md`. A version bump that changes nothing is
listed as "identical" (it exists to keep a set of prompts aligned, never to hide an edit); a real
change shows the lines added and removed, so a reviewer sees the change behind every version bump.
"""

from __future__ import annotations

import argparse
import difflib
import re
import sys
from itertools import pairwise
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PROMPTS = ROOT / "src" / "arena" / "llm" / "prompts"
OUT = ROOT / "docs" / "prompts" / "CHANGES.md"
NAME = re.compile(r"^(?P<name>.+)_v(?P<n>\d+)\.md$")


def families(directory: Path = PROMPTS) -> dict[str, dict[int, str]]:
    """{prompt name: {version: text}} for every prompt file."""
    out: dict[str, dict[int, str]] = {}
    for path in sorted(directory.glob("*.md")):
        m = NAME.match(path.name)
        if m:
            out.setdefault(m["name"], {})[int(m["n"])] = path.read_text("utf-8")
    return out


def render(fams: dict[str, dict[int, str]]) -> str:
    """The Markdown report."""
    lines = [
        "# Prompt changes between versions",
        "",
        "Generated by `scripts/prompt_diff.py` from `src/arena/llm/prompts/`; do not edit by hand.",
        "A version that changes nothing is marked identical. A live forecaster's prompt never",
        "changes in place (I8): a change is a new version, and the diff below is what changed.",
        "",
    ]
    for name, versions in sorted(fams.items()):
        nums = sorted(versions)
        lines += [f"## `{name}`", "", f"Versions: {', '.join(f'v{n}' for n in nums)}.", ""]
        if len(nums) == 1:
            lines += ["Only one version.", ""]
        for a, b in pairwise(nums):
            if versions[a] == versions[b]:
                lines += [f"- v{a} to v{b}: identical text.", ""]
                continue
            diff = [
                ln
                for ln in difflib.unified_diff(
                    versions[a].splitlines(), versions[b].splitlines(), lineterm="", n=0
                )
                if not ln.startswith(("---", "+++", "@@"))
            ]
            lines += [
                f"- v{a} to v{b}: {len(diff)} changed lines.",
                "",
                "```diff",
                *diff,
                "```",
                "",
            ]
    return "\n".join(lines).rstrip() + "\n"


def main() -> int:
    """CLI entry point."""
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text = render(families())
    if args.check:
        if not OUT.is_file() or OUT.read_text("utf-8") != text:
            print("docs/prompts/CHANGES.md is stale: run python scripts/prompt_diff.py")
            return 1
        print("prompt changes up to date")
        return 0
    OUT.write_text(text, "utf-8")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
