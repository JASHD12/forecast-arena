"""Write the card of the `quant-r2` estimate selection (T399): `docs/lab/quant-estimate-r2.md`.

    python scripts/quant_estimate_study.py          # writes the card
    python scripts/quant_estimate_study.py --check  # fails if the card is stale

Free and offline: stored contexts and outcomes of the two frozen golden sets, no model call.
Pre-registration: `lab/prereg/agent-quant-r2.md`.
"""

from __future__ import annotations

import hashlib
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from arena.evals.golden import load  # noqa: E402
from arena.lab import quant_estimate as qe  # noqa: E402

OUT = ROOT / "docs" / "lab" / "quant-estimate-r2.md"
PREREG = ROOT / "lab" / "prereg" / "agent-quant-r2.md"


def _table(rows: dict[str, dict[str, float]], names: list[str]) -> list[str]:
    out = ["| Template | " + " | ".join(names) + " |", "|---|" + "---|" * len(names)]
    for template, vals in sorted(rows.items()):
        out.append(f"| {template} | " + " | ".join(f"{vals[n]:.4f}" for n in names) + " |")
    return out


def render() -> str:
    """The card text."""
    october, sha_o = load(ROOT / "evals" / "golden" / "power-2026-10.jsonl")
    november, sha_n = load(ROOT / "evals" / "golden" / "power-2026-11a.jsonl")
    sel = qe.selection(october)
    thr_names = list(qe.CANDIDATES_THRESHOLD)
    up_names = list(qe.CANDIDATES_UP)
    thr = {t: v for t, v in sel.items() if t != "up_vs_today"}
    allv = {
        n: sum(thr[t][n] for t in thr) / len(thr)
        for n in thr_names  # equal items per template
    }
    conf = qe.confirmation(november)
    d = conf["diff"]
    lines = [
        "# The `quant-r2` reference estimate: selection and one-time check",
        "",
        "**EVALUATION: an experiment of the lab, not the live record (SPEC 17).** Free and offline: stored contexts and outcomes,",  # noqa: E501 - generated card text
        "no model call. Generated by `scripts/quant_estimate_study.py`; pre-registered in `lab/prereg/agent-quant-r2.md`"  # noqa: E501 - generated card text
        f" (sha256 `{hashlib.sha256(PREREG.read_bytes()).hexdigest()[:12]}`).",
        "",
        f"## Selection on the October set (`power-2026-10.jsonl`, {len(october)} items, sha256 `{sha_o[:12]}`)",  # noqa: E501 - generated card text
        "",
        "Brier per template, lower is better (31 items each). One rule for all threshold templates, no per-template exceptions.",  # noqa: E501 - generated card text
        "",
        *_table(thr, thr_names),
        "",
        "Mean over the five threshold templates: "
        + ", ".join(f"{n} {v:.4f}" for n, v in allv.items())
        + ".",
        "",
        "`up_vs_today`:",
        "",
        *_table({"up_vs_today": sel["up_vs_today"]}, up_names),
        "",
        f"## One-time check on the November set (`power-2026-11a.jsonl`, {conf['n']} items, sha256 `{sha_n[:12]}`)",  # noqa: E501 - generated card text
        "",
        "H-Q5: the r2 estimate alone against the r1 estimate alone, paired day-block 95% interval.",
        "",
        f"- r2 Brier {conf['brier_r2']:.4f}, r1 Brier {conf['brier_r1']:.4f} over {conf['n']} questions.",  # noqa: E501 - generated card text
        f"- Difference r2 minus r1: {d.estimate:+.4f}, 95% interval [{d.low:+.4f}, {d.high:+.4f}] over {d.days} days"  # noqa: E501 - generated card text
        f" ({'interval excludes zero' if d.excludes_zero else 'interval includes zero'}).",
        "",
        "| Template | r2 | r1 |",
        "|---|---|---|",
        *(f"| {t} | {a:.4f} | {b:.4f} |" for t, (a, b) in conf["per_template"].items()),
        "",
        "## What this does and does not show",
        "",
        "- This is the estimate alone, not the agent. The paid comparison of `agent_quant` r2 with `agent` (H-Q6, H-Q7) is a separate run.",  # noqa: E501 - generated card text
        "- Electricity only, the one topic a replay can reproduce; the six questions of a day are correlated, so intervals resample whole days.",  # noqa: E501 - generated card text
        "- The November check is evaluated once, after the estimate was frozen; no later change is made because of it (I8).",  # noqa: E501 - generated card text
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    """Write the card, or with --check compare it."""
    text = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print("quant estimate card is stale: run python scripts/quant_estimate_study.py")
            return 1
        print("quant estimate card up to date")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
