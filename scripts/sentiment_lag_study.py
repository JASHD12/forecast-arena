"""Write the lag table of news tone and volume against crypto moves (T402).

The card is `docs/lab/sentiment-lag.md`.

    python scripts/sentiment_lag_study.py          # writes the card
    python scripts/sentiment_lag_study.py --check  # fails if the card is stale

Offline, from the recorded CoinGecko and GDELT fixtures (the data of the pre-registered backtest).
"""

from __future__ import annotations

import gzip
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from arena.backtest import sentiment as B  # noqa: E402
from arena.domains.crypto import COINS  # noqa: E402
from arena.lab.sentiment_lag import lag_table  # noqa: E402
from arena.sources.coingecko import parse_daily  # noqa: E402

OUT = ROOT / "docs" / "lab" / "sentiment-lag.md"
CG = ROOT / "tests" / "fixtures" / "coingecko"
GDELT = ROOT / "tests" / "fixtures" / "gdelt" / "history"
LABEL = {
    1: "day after the move (news reacts)",
    0: "same day",
    -1: "day before",
    -2: "two days before",
    -3: "three days before (what the as-of rule allows)",
}


def _f(v: float | None) -> str:
    return "n/a" if v is None else f"{v:+.3f}"


def render() -> str:
    """The card text."""
    prices = {
        c: parse_daily(json.loads(gzip.decompress((CG / f"{c}_365d.json.gz").read_bytes())))
        for c in COINS
    }
    rows = lag_table(prices, B.load_news(GDELT))
    lines = [
        "# News tone and volume against crypto moves, by day offset",
        "",
        "**Descriptive, offline; a lab note, not the live record (SPEC 17).** Generated by",
        "`scripts/sentiment_lag_study.py` from the recorded CoinGecko and GDELT fixtures.",
        "It explains the pre-registered result (`docs/lab/sentiment.md`) and changes no decision.",
        "",
        "For a move on day D, the pooled correlation with the GDELT day D + k, over five coins:",
        "the article-volume surprise against the absolute move, and the per-coin demeaned tone",
        "against the signed move. Days with no articles and GDELT-wide outages are left out.",
        "",
        "| GDELT day relative to the move | Volume surprise vs absolute move | n | "
        "Tone vs signed move | n |",
        "|---|---|---|---|---|",
        *(
            f"| {LABEL[int(r['offset'])]} | {_f(r['corr_volume_abs_move'])} | {r['n_volume']} | "
            f"{_f(r['corr_tone_move'])} | {r['n_tone']} |"
            for r in rows
        ),
        "",
        "- A question on batch day B sees GDELT day B-2 at most (a GDELT day counts from the",
        "  next day 12:00 UTC) and asks about the move of day B+1: that is the last row.",
        "- Correlation is not a forecast and these are pooled over coins and days that are not",
        "  independent; read the pattern, not the third decimal.",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    """Write the card, or with --check compare it."""
    text = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print("sentiment lag card is stale: run python scripts/sentiment_lag_study.py")
            return 1
        print("sentiment lag card up to date")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
